function bandFor(s: Story): AgeBand {
  return s.minAge <= 5 ? "4-6" : s.minAge <= 8 ? "7-9" : "10-12";
}

const TONES: ReadonlySet<string> = new Set(["english", "math", "science", "gk", "story", "brain", "creativity", "habit"]);
const isTone = (c: string): c is HubStory["tone"] => TONES.has(c);

/** Existing English stories, unchanged, adapted to the hub shape. */
const EN_HUB_STORIES: HubStory[] = EN_STORIES.map((s) => ({
  id: `en-${s.id}`, lang: "en", age: bandFor(s), title: s.title, scene: s.scene,
  tone: isTone(s.sceneColor) ? s.sceneColor : "story",
  paragraphs: s.paragraphs, moral: s.moral, source: "original", questions: s.questions,
}));

export const HUB_STORIES: HubStory[] = [...BN_STORIES, ...EN_HUB_STORIES];

export function findHubStory(id: string): HubStory | undefined {
  return HUB_STORIES.find((s) => s.id === id);
}
